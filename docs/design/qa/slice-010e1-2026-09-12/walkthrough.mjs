import { chromium } from '/Users/karrad/projects/crm/web/node_modules/playwright-core/index.mjs';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const fixture=JSON.parse(fs.readFileSync('/private/tmp/crm-core-change-ui.json','utf8'));
const output='/Users/karrad/projects/crm/docs/design/qa/slice-010e1-2026-09-12';
fs.mkdirSync(output,{recursive:true});
const records=[];
const record=(step,data={})=>{const value={step,...data};records.push(value);console.log(JSON.stringify(value));};
const browser=await chromium.launch({headless:true,executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
const context=await browser.newContext({viewport:{width:1440,height:1050},storageState:'/private/tmp/crm-010e1-qa/browser-state.json'});
const page=await context.newPage();
const errors=[];
page.on('pageerror',error=>errors.push(error.message));
try {
  await page.goto('http://127.0.0.1:5202/manage/migration');
  const panel=page.getByTestId('core-change-reports');
  await panel.waitFor();
  await page.getByLabel('Saved change report',{exact:true}).selectOption(fixture.cancelled_report_id);
  await page.getByRole('heading',{name:'Cancelled change report',exact:true}).waitFor();
  assert.equal(await panel.getByTestId('core-change-rows').count(),0);
  assert.equal(await panel.getByRole('button',{name:'Resume change report',exact:true}).count(),0);
  record('cancelled-report-preserves-unpublished-boundary');
  await page.getByLabel('Saved change report',{exact:true}).selectOption(fixture.report_id);
  await page.getByRole('heading',{name:'Completed change report',exact:true}).waitFor();
  const requests=[];
  let dropped=false;
  await page.route('**/api/migrations/fub/core-change-reports',async route=>{
    if(route.request().method()!=='POST') return route.continue();
    requests.push(route.request().postDataJSON());
    if(!dropped){
      dropped=true;
      const response=await route.fetch();
      assert.equal(response.status(),201);
      assert.equal((await response.json()).report_id,fixture.report_id);
      await route.abort('failed');
    }else await route.continue();
  });
  await page.getByLabel('Newer retained core capture',{exact:true}).selectOption(fixture.newer_snapshot_id);
  await panel.getByRole('button',{name:'Assess changes',exact:true}).click();
  const retry=panel.getByRole('button',{name:'Retry the same report request',exact:true});
  await retry.waitFor();
  await retry.click();
  await retry.waitFor({state:'hidden'});
  assert.equal(requests.length,2);
  assert.deepEqual(requests[0],requests[1]);
  record('actual-commit-dropped-response-same-request-recovery',{request_id:requests[0].request_id,report_id:fixture.report_id});
  await page.unroute('**/api/migrations/fub/core-change-reports');
  await page.getByLabel('Comparison family',{exact:true}).selectOption('people');
  await page.getByLabel('Comparison result',{exact:true}).selectOption('not_seen_again');
  const rows=page.getByTestId('core-change-rows');
  await rows.getByText('1 on this page',{exact:true}).waitFor();
  assert.match(await rows.innerText(),/People · 103/);
  assert.match(await rows.innerText(),/does not establish deletion/);
  await rows.scrollIntoViewIfNeeded();
  await page.screenshot({path:output+'/desktop.png'});
  record('filtered-absence-with-no-deletion-claim',{family:'people',disposition:'not_seen_again',rows:1});
  await page.getByLabel('Comparison family',{exact:true}).selectOption('notes');
  await page.getByLabel('Comparison result',{exact:true}).selectOption('unresolved');
  await rows.getByText('1 on this page',{exact:true}).waitFor();
  await rows.getByRole('button',{name:'Inspect comparison 11',exact:true}).click();
  const detail=rows.getByRole('region',{name:'Source comparison detail'});
  await detail.getByRole('heading',{name:'Representative retained evidence',exact:true}).waitFor();
  assert.match(await detail.innerText(),/Note content inaccessible/);
  assert.match(await detail.innerText(),/These references are not exhaustive/);
  await page.setViewportSize({width:390,height:844});
  await detail.scrollIntoViewIfNeeded();
  const size=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth}));
  assert.ok(size.scroll<=size.width,JSON.stringify(size));
  assert.ok(!/SYNTHETIC_UNREADABLE_BODY|SENTINEL_PRIVATE_BODY/.test(await panel.innerText()));
  await page.screenshot({path:output+'/narrow-note-detail.png'});
  record('narrow-inaccessible-note-detail',{...size,references:'representative',bodySentinelAbsent:true});
  const evidenceButton=detail.getByRole('button',{name:/Review newer snapshot for evidence/}).first();
  await evidenceButton.click();
  await page.waitForFunction(id=>document.querySelector('[data-testid="snapshot-selection"]')?.value===id,fixture.newer_snapshot_id);
  await page.getByTestId('snapshot-state').waitFor();
  record('authorized-snapshot-navigation',{snapshot_id:fixture.newer_snapshot_id});
  await page.reload();
  await page.getByLabel('Saved change report',{exact:true}).selectOption(fixture.report_id);
  await page.getByRole('heading',{name:'Completed change report',exact:true}).waitFor();
  record('reload-recovers-retained-report',{report_id:fixture.report_id});
  assert.deepEqual(errors,[]);
  record('finished',{pageErrors:errors,mockedResponses:false,controlledFault:'one accepted POST response discarded'});
} catch(error) {
  record('failed',{message:error.message});
  await page.screenshot({path:'/private/tmp/crm-010e1-qa/failure.png'}).catch(()=>{});
  throw error;
} finally {
  fs.writeFileSync(output+'/walkthrough.jsonl',records.map(v=>JSON.stringify(v)).join('\n')+'\n');
  await browser.close();
}
